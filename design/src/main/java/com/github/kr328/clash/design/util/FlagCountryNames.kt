private val countryPatterns = COUNTRY_NAMES.map { (name, code) ->
    Regex("""(?<![\p{L}\p{N}])${Regex.escape(name)}(?![\p{L}\p{N}])""", RegexOption.IGNORE_CASE) to code
}

internal fun countryCodeFromName(name: String): String? =
    countryPatterns.firstOrNull { (pattern, _) -> pattern.containsMatchIn(name) }?.second
