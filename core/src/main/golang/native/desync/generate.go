// Request describes a desync-only profile.
type Request struct {
	// Services are IDs of Services().
	Services []string `json:"services"`
	// CustomDomains are routed through one extra proxy, desync-custom;
	// subdomains included.
	CustomDomains []string `json:"customDomains"`
	// StrategyPresetID is the TCP preset of every proxy; empty is automatic:
	// each route gets a fallback group over AutoCandidates (see
	// autoCandidates), or the catalog's defaultTcp where fewer than two of
	// them are available.
	StrategyPresetID string `json:"strategyPresetId"`
	// UDPPresetID optionally adds a UDP burst preset to every proxy.
	UDPPresetID string `json:"udpPresetId,omitempty"`
	// RejectQUIC rejects UDP/443 through the desync proxies so that apps fall
	// back to TCP, which desync transforms. Default: on without a UDP preset.
	RejectQUIC *bool `json:"rejectQuic,omitempty"`
}

// Result carries either the YAML or the reason there is none.
type Result struct {
	YAML  string `json:"yaml,omitempty"`
	Error string `json:"error,omitempty"`
}

// CustomProxyName is the proxy that carries Request.CustomDomains.
const CustomProxyName = "desync-custom"

const maxCustomDomains = 1000

const generatedHeader = "# Desync-only profile generated by ClashFest: the listed domains go through\n" +
	"# type: desync proxies (a direct connection with a reshaped TLS ClientHello),\n" +
	"# everything else DIRECT.\n"

// ProxyName is the generated proxy of a service, or with automatic strategy
// selection its fallback group.
func ProxyName(serviceID string) string { return "desync-" + serviceID }

// AutoCandidates are the TCP presets automatic selection tries, in order:
// cheapest first, chosen from desync-probe measurements on Russian mobile
// networks, where YouTube passes only with TLS record splits and Instagram
// only with a TCP split or an out-of-band byte. Presets the device cannot use
// are left out.
var AutoCandidates = []string{"tlsrec-1s", "tlsrec-1s-split-1", "oob-1", "tlsrec-3s"}

// Automatic selection checks each candidate once when the profile loads and
// then every autoInterval while the route is in use (lazy), so an idle
// profile sends no checks.
const (
	autoInterval  = 600
	autoTimeoutMS = 5000
)

func candidateName(route, preset string) string { return route + "~" + preset }

// autoCandidates returns the presets of AutoCandidates the catalog offers, in
// AutoCandidates order.
func autoCandidates(catalog Catalog) []Preset {
	var out []Preset
	for _, name := range AutoCandidates {
		for _, p := range catalog.TCP {
			if p.Name == name {
				out = append(out, p)
				break
			}
		}
	}
	return out
}

var hostname = regexp.MustCompile(`^([a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?$`)

// normalizeDomain accepts a host name, a "*." or "." suffix pattern, or a
// URL, and returns the bare lower-case host.
func normalizeDomain(s string) (string, error) {
	d := strings.ToLower(strings.TrimSpace(s))
	if i := strings.Index(d, "://"); i >= 0 {
		d = d[i+3:]
	}
	if i := strings.IndexAny(d, "/?#"); i >= 0 {
		d = d[:i]
	}
	if i := strings.LastIndexByte(d, ':'); i >= 0 && !strings.Contains(d[i:], "]") {
		d = d[:i]
	}
	d = strings.TrimPrefix(d, "*.")
	d = strings.Trim(d, ".")
	if len(d) > 253 || !hostname.MatchString(d) {
		return "", fmt.Errorf("custom domain %q is not a host name", s)
	}
	return d, nil
}

type generatedProxy struct {
	Name    string `yaml:"name"`
	Type    string `yaml:"type"`
	Options `yaml:",inline"`
}

type generatedGroup struct {
	Name     string   `yaml:"name"`
	Type     string   `yaml:"type"`
	Proxies  []string `yaml:"proxies"`
	URL      string   `yaml:"url"`
	Interval int      `yaml:"interval"`
	Timeout  int      `yaml:"timeout"`
	Lazy     bool     `yaml:"lazy"`
}

// generatedDNS is the app's default fake-ip DNS (patchDns) with the system
// resolver only. Measured on Russian mobile networks, plain DNS to public
// resolvers answers blocked names with forged NXDOMAIN (8.8.4.4, 1.0.0.1) or
// with addresses the network drops at TCP connect (223.5.5.5, 119.29.29.29 for
// Instagram), and the engine takes whichever answer comes first; the
// operator's resolver returned addresses desync gets through to.
type generatedDNS struct {
	Enable       bool     `yaml:"enable"`
	EnhancedMode string   `yaml:"enhanced-mode"`
	FakeIPRange  string   `yaml:"fake-ip-range"`
	FakeIPFilter []string `yaml:"fake-ip-filter"`
	NameServer   []string `yaml:"nameserver"`
}

// generatedSniffer reads the server name of TLS and QUIC connections an app
// opens to a bare IP (no DNS through the core, as Meta's apps do), so that
// the domain rules - and reject-quic - apply to them too. The destination
// stays the address the app chose. The fake-ip range is skipped: a fake IP
// the core has no name for (an app reusing an answer of an earlier session)
// would otherwise be dialed as an address; dropped, the app asks DNS again.
type generatedSniffer struct {
	Enable         bool                           `yaml:"enable"`
	OverrideDest   bool                           `yaml:"override-destination"`
	ParsePureIP    bool                           `yaml:"parse-pure-ip"`
	SkipDstAddress []string                       `yaml:"skip-dst-address"`
	Sniff          map[string]generatedSniffPorts `yaml:"sniff"`
}

type generatedSniffPorts struct {
	Ports []int `yaml:"ports"`
}

type generatedProfile struct {
	Mode        string           `yaml:"mode"`
	DNS         generatedDNS     `yaml:"dns"`
	Sniffer     generatedSniffer `yaml:"sniffer"`
	Proxies     []generatedProxy `yaml:"proxies"`
	ProxyGroups []generatedGroup `yaml:"proxy-groups,omitempty"`
	Rules       []string         `yaml:"rules"`
}

// GenerateConfig builds the profile for the catalog of this device and checks
// it with the engine's own parser (snapshot.ValidateBytes).
func GenerateConfig(req Request) (string, error) {
	return generateConfig(req, catalogFor(effectiveCapabilities()))
}

// serviceRoute is one destination of the request: a service or the custom domains.
type serviceRoute struct {
	proxy   string
	domains []string
	testURL string
}

// plan is what a request resolves to on a catalog: its routes, the TCP
// presets each route gets (more than one: automatic selection) and the
// options of a proxy for a preset.
type plan struct {
	routes    []serviceRoute
	tcps      []Preset
	optionsOf func(Preset) Options
}

func planFor(req Request, catalog Catalog) (plan, error) {
	var routes []serviceRoute
	seenService := map[string]bool{}
	for _, id := range req.Services {
		s, ok := serviceByID(id)
		if !ok {
			return plan{}, fmt.Errorf("unknown service %q", id)
		}
		if seenService[id] {
			continue
		}
		seenService[id] = true
		routes = append(routes, serviceRoute{ProxyName(s.ID), s.Domains, s.TestURL})
	}
	if len(req.CustomDomains) > maxCustomDomains {
		return plan{}, fmt.Errorf("at most %d custom domains", maxCustomDomains)
	}
	var custom []string
	seenDomain := map[string]bool{}
	for _, raw := range req.CustomDomains {
		if strings.TrimSpace(raw) == "" {
			continue
		}
		d, err := normalizeDomain(raw)
		if err != nil {
			return plan{}, err
		}
		if !seenDomain[d] {
			seenDomain[d] = true
			custom = append(custom, d)
		}
	}
	if len(custom) > 0 {
		routes = append(routes, serviceRoute{CustomProxyName, custom, "https://" + custom[0] + "/"})
	}
	if len(routes) == 0 {
		return plan{}, errors.New("choose at least one service or custom domain")
	}

	var tcps []Preset
	if req.StrategyPresetID == "" {
		if auto := autoCandidates(catalog); len(auto) >= 2 {
			tcps = auto
		}
	}
	if tcps == nil {
		presetID := req.StrategyPresetID
		if presetID == "" {
			presetID = catalog.DefaultTCP
		}
		if presetID == "" {
			return plan{}, errors.New("no desync strategy is available on this device")
		}
		tcp, err := catalog.find(catalog.TCP, "tcp", presetID)
		if err != nil {
			return plan{}, err
		}
		tcps = []Preset{tcp}
	}
	var udp *UDPOptions
	if req.UDPPresetID != "" {
		p, err := catalog.find(catalog.UDP, "udp", req.UDPPresetID)
		if err != nil {
			return plan{}, err
		}
		udp = p.Options.UDP
	}
	rejectQUIC := udp == nil
	if req.RejectQUIC != nil {
		rejectQUIC = *req.RejectQUIC
	}
	return plan{routes: routes, tcps: tcps, optionsOf: func(tcp Preset) Options {
		opts := tcp.Options
		opts.UDP = udp
		opts.RejectQUIC = rejectQUIC
		return opts
	}}, nil
}

func generateConfig(req Request, catalog Catalog) (string, error) {
	pl, err := planFor(req, catalog)
	if err != nil {
		return "", err
	}
	routes, tcps, optionsOf := pl.routes, pl.tcps, pl.optionsOf

	profile := generatedProfile{Mode: "rule", DNS: generatedDNS{
		Enable:       true,
		EnhancedMode: "fake-ip",
		FakeIPRange:  fakeipdefaults.Range,
		FakeIPFilter: fakeipdefaults.Filter(),
		NameServer:   []string{"system://"},
	}, Sniffer: generatedSniffer{
		Enable:         true,
		ParsePureIP:    true,
		SkipDstAddress: []string{fakeipdefaults.Range},
		Sniff: map[string]generatedSniffPorts{
			"TLS":  {Ports: []int{443}},
			"QUIC": {Ports: []int{443}},
		},
	}}
	for _, r := range routes {
		if len(tcps) == 1 {
			profile.Proxies = append(profile.Proxies, generatedProxy{Name: r.proxy, Type: "desync", Options: optionsOf(tcps[0])})
		} else {
			group := generatedGroup{
				Name: r.proxy, Type: "fallback", URL: r.testURL,
				Interval: autoInterval, Timeout: autoTimeoutMS, Lazy: true,
			}
			for _, tcp := range tcps {
				name := candidateName(r.proxy, tcp.Name)
				profile.Proxies = append(profile.Proxies, generatedProxy{Name: name, Type: "desync", Options: optionsOf(tcp)})
				group.Proxies = append(group.Proxies, name)
			}
			profile.ProxyGroups = append(profile.ProxyGroups, group)
		}
		for _, d := range r.domains {
			profile.Rules = append(profile.Rules, "DOMAIN-SUFFIX,"+d+","+r.proxy)
		}
	}
	profile.Rules = append(profile.Rules, "MATCH,DIRECT")

	body, err := yaml.Marshal(&profile)
	if err != nil {
		return "", err
	}
	out := generatedHeader + string(body)
	if msg := snapshot.ValidateBytes([]byte(out)); msg != "" {
		return "", fmt.Errorf("the engine rejects the generated profile: %s", msg)
	}
	return out, nil
}

// GenerateConfigJSON is GenerateConfig for the bridge: a JSON Request in, a
// JSON Result out.
func GenerateConfigJSON(request string) string {
	var res Result
	var req Request
	if err := json.Unmarshal([]byte(request), &req); err != nil {
		res.Error = "malformed request: " + err.Error()
	} else if y, err := GenerateConfig(req); err != nil {
		res.Error = err.Error()
	} else {
		res.YAML = y
	}
	b, _ := json.Marshal(res)
	return string(b)
}
