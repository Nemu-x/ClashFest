package com.github.kr328.clash.service.util

import com.github.kr328.clash.core.model.DesyncConfigRequest
import com.github.kr328.clash.core.model.DesyncGeneratedConfig
import com.github.kr328.clash.service.model.DesyncProfileSettings
import com.github.kr328.clash.service.model.ProxyHardeningMode
import java.io.File
import java.nio.file.Files
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertFailsWith
import kotlin.test.assertFalse
import kotlin.test.assertNull
import kotlin.test.assertTrue

class DesyncProfileConfigTest {
    /** Shape of `cfa/native/desync` GenerateConfig output (generate_test.go). */
    private val generated = """
        # Desync-only profile generated by ClashFest: the listed domains go through
        # type: desync proxies (a direct connection with a reshaped TLS ClientHello),
        # everything else DIRECT.
        mode: rule
        proxies:
            - name: desync-youtube
              type: desync
              tlsrec: 1+s
              reject-quic: true
            - name: desync-custom
              type: desync
              tlsrec: 1+s
              reject-quic: true
        rules:
            - DOMAIN-SUFFIX,youtube.com,desync-youtube
            - DOMAIN-SUFFIX,example.org,desync-custom
            - MATCH,DIRECT
    """.trimIndent() + "\n"

    private class RecordingGenerator(private val result: DesyncGeneratedConfig) : (DesyncConfigRequest) -> DesyncGeneratedConfig {
        val requests = mutableListOf<DesyncConfigRequest>()
        override fun invoke(request: DesyncConfigRequest): DesyncGeneratedConfig {
            requests += request
            return result
        }
    }

    @Test
    fun settings_map_to_the_bridge_request() {
        val request = DesyncProfileSettings(
            services = listOf("youtube", " discord ", "", "youtube"),
            customDomains = listOf(" Example.org ", "", "example.org", "Example.org"),
            strategyPresetId = " s30879a4293 ",
            udpPresetId = "",
        ).toRequest()

        assertEquals(listOf("youtube", "discord"), request.services)
        // Trimmed and de-duplicated as typed; normalising case is the generator's job.
        assertEquals(listOf("Example.org", "example.org"), request.customDomains)
        assertEquals("s30879a4293", request.strategyPresetId)
        assertEquals("", request.udpPresetId)
        assertNull(request.rejectQuic)
    }

    @Test
    fun defaults_are_youtube_and_discord_with_automatic_strategy() {
        val settings = DesyncProfileSettings()
        assertEquals(listOf("youtube", "discord"), settings.services)
        assertTrue(settings.isAutomaticStrategy)
        assertEquals("", settings.toRequest().strategyPresetId, "blank = the catalog's defaultTcp")
    }

    @Test
    fun json_round_trips_and_tolerates_unknown_or_malformed_input() {
        val settings = DesyncProfileSettings(listOf("discord"), listOf("example.org"), "s1", "u2")
        assertEquals(settings, DesyncProfileSettings.decode(settings.encode()))
        assertEquals(
            DesyncProfileSettings(services = listOf("youtube")),
            DesyncProfileSettings.decode("""{"services":["youtube"],"calibration":{"tried":[]}}"""),
        )
        assertNull(DesyncProfileSettings.decode(null))
        assertNull(DesyncProfileSettings.decode(""))
        assertNull(DesyncProfileSettings.decode("{not json"))
    }

    @Test
    fun domain_input_is_split_on_lines_commas_and_spaces() {
        assertEquals(
            listOf("a.com", "b.org", "c.net"),
            DesyncProfileSettings.parseDomains("a.com, b.org\n\n c.net  a.com;"),
        )
        assertEquals(emptyList(), DesyncProfileSettings.parseDomains("  \n "))
    }

    @Test
    fun regeneration_writes_the_generated_yaml() {
        val dir = Files.createTempDirectory("desync").toFile()
        try {
            File(dir, "config.yaml").writeText("stale: true\n")
            val generator = RecordingGenerator(DesyncGeneratedConfig(yaml = generated))
            val settings = DesyncProfileSettings(services = listOf("youtube"), customDomains = listOf("example.org"))

            DesyncProfileConfig.writeTo(dir, settings.encode(), generator)

            assertEquals(generated, File(dir, "config.yaml").readText())
            assertEquals(listOf(settings.toRequest()), generator.requests)
        } finally {
            dir.deleteRecursively()
        }
    }

    @Test
    fun malformed_stored_settings_regenerate_from_the_defaults() {
        val generator = RecordingGenerator(DesyncGeneratedConfig(yaml = generated))
        DesyncProfileConfig.generate("{broken", generator)
        assertEquals(listOf(DesyncProfileSettings().toRequest()), generator.requests)
    }

    @Test
    fun a_generator_error_leaves_the_old_config_in_place() {
        val dir = Files.createTempDirectory("desync").toFile()
        try {
            File(dir, "config.yaml").writeText("old: true\n")
            val generator = RecordingGenerator(DesyncGeneratedConfig(error = "choose at least one service or custom domain"))

            val e = assertFailsWith<DesyncProfileConfig.GenerationException> {
                DesyncProfileConfig.writeTo(dir, DesyncProfileSettings(services = emptyList()).encode(), generator)
            }
            assertEquals("choose at least one service or custom domain", e.message)
            assertEquals("old: true\n", File(dir, "config.yaml").readText())
        } finally {
            dir.deleteRecursively()
        }
    }

    @Test
    fun check_reports_the_reason_or_null() {
        assertNull(DesyncProfileConfig.check(DesyncProfileSettings(), RecordingGenerator(DesyncGeneratedConfig(yaml = generated))))
        assertEquals(
            "custom domain \"bad domain\" is not a host name",
            DesyncProfileConfig.check(
                DesyncProfileSettings(customDomains = listOf("bad domain")),
                RecordingGenerator(DesyncGeneratedConfig(error = "custom domain \"bad domain\" is not a host name")),
            ),
        )
        assertEquals(
            "desync profile generation failed",
            DesyncProfileConfig.check(DesyncProfileSettings(), RecordingGenerator(DesyncGeneratedConfig())),
        )
    }

    @Test
    fun composition_and_hardening_keep_the_generated_profile() {
        val geo = GeoDataUrls(geoIp = "", geoSite = "", mmdb = "", asn = "")
        for (mode in ProxyHardeningMode.values()) {
            val out = ConfigComposer.compose(generated, UserLayer(), geo, mode)
            assertTrue("type: desync" in out, "[$mode] desync proxies survive: $out")
            assertTrue("reject-quic: true" in out, "[$mode] $out")
            assertTrue("DOMAIN-SUFFIX,youtube.com,desync-youtube" in out, "[$mode] $out")
            assertTrue("MATCH,DIRECT" in out, "[$mode] $out")
            assertFalse("proxy-groups" in out && "desync-youtube" !in out, "[$mode] $out")
        }
    }
}
